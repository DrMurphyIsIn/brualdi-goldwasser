"""Emit LeanCherry/WinExt2Boxes.lean from boxes2.json: one BoxP literal + BoxOK2 proof per box, and the cover theorem.

Run from this directory: python3 emit_lean2.py (it overwrites ../LeanCherry/WinExt2Boxes.lean)."""
import json, sys
from fractions import Fraction as Q
from decimal import Decimal, getcontext
getcontext().prec = 60
def dec(s):
    q = Q(s); d = Decimal(q.numerator) / Decimal(q.denominator)
    t = format(d.normalize(), 'f')
    assert Q(t) == q, (s, t)
    return t if not t.startswith('-') else '(' + t + ')'
boxes = json.load(open('boxes2.json'))
boxes = sorted(boxes, key=lambda p: Q(p['a']))
limit = int(sys.argv[1]) if len(sys.argv) > 1 else len(boxes)
boxes = boxes[-limit:] if limit < len(boxes) else boxes
order = ['a', 'b', 'sl', 'sh', 'Fl', 'Fh', 'Vh', 'Dl', 'σl', 'σh', 'εh', 'εl', 'ydl', 'ydh', 'wl', 'wh', 'κl', 'κh', 'Gh']
L0 = dec(boxes[0]['a'])
out = []
out.append("/-\nLeanCherry.WinExt2Boxes -- the window extended to [2, 2.35], part 3 (GENERATED by scripts/emit_lean2.py from scripts/boxes2.json; do not edit):\n"
           f"the box constants and their BoxOK certificates covering [{L0}, 2.35].\n-/")
out.append("import LeanCherry.WinExt2Assemble\n\nopen Real\n\nnamespace LeanCherry\n\nnoncomputable section\n\nnamespace WinExt2\n")
for i, p in enumerate(boxes):
    vals = ", ".join(dec(p[k]) for k in order)
    out.append(f"/-- box {i}: [{dec(p['a'])}, {dec(p['b'])}] -/\ndef bp{i} : BoxP := ⟨{vals}⟩\n")
    out.append(f"theorem bok{i} : BoxOK2 bp{i} := by\n  constructor <;> simp only [bp{i}] <;> norm_num\n")
# cover
for i in range(len(boxes) - 1):
    assert Q(boxes[i]['b']) == Q(boxes[i + 1]['a'])
assert Q(boxes[-1]['b']) == Q('2.35')
n = len(boxes)
out.append(f"theorem cov{n-1} (l : ℝ) (h1 : bp{n-1}.a ≤ l) (h2 : l ≤ 2.35) : WFacts2 l :=\n  (bok{n-1}).wfacts2 h1 (by simp only [bp{n-1}]; linarith)\n")
for i in range(n - 2, -1, -1):
    out.append(f"theorem cov{i} (l : ℝ) (h1 : bp{i}.a ≤ l) (h2 : l ≤ 2.35) : WFacts2 l := by")
    out.append(f"  by_cases c : l ≤ bp{i}.b")
    out.append(f"  · exact (bok{i}).wfacts2 h1 c")
    out.append(f"  · exact cov{i+1} l (by simp only [bp{i+1}]; simp only [bp{i}] at c; linarith) h2\n")
out.append(f"/-- every l in [{L0}, 2.35] lies in some certified box -/")
out.append(f"theorem wfacts_ext2 (l : ℝ) (h1 : {L0} ≤ l) (h2 : l ≤ 2.35) : WFacts2 l :=\n  cov0 l (by simp only [bp0]; linarith) h2")
out.append("\nend WinExt2\n\nend\n\nend LeanCherry\n")
open('../LeanCherry/WinExt2Boxes.lean', 'w').write("\n".join(out))
print("emitted", len(boxes), "boxes from", L0)
